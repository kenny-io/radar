// DEV ONLY. A tiny HTTPS receiver for Radar's Webhook connector (Node built-ins only).
// - Verifies Radar-Signature exactly as docs/webhook.md describes (HMAC-SHA256 of "{t}.{raw body}", keyed with the full
//   whsec_ secret, constant-time compare, 5-minute tolerance) and answers 401 "bad signature" otherwise.
// - Appends every request to .data/connectors/webhook-received.jsonl ({ at, path, headers, verified, reason, body }).
// - For article.published, replies { ok, url } with a page it serves itself: GET /posts/{slug} renders the received HTML,
//   so "View post" opens something real.
// - Accepted secrets: RADAR_IT_WEBHOOK_SECRET (generated by webhook-up.sh for the integration tests) plus every line of
//   .data/connectors/webhook-secrets.txt (append the secret Radar shows when you add the webhook connection:
//   scripts/connectors/webhook-secret.sh whsec_…). Both are re-read on every request.
// - Failure drills: POST /hook?status=500 answers that status; GET /__received lists what arrived (JSON).
// Run via scripts/connectors/webhook-up.sh (it creates the self-signed certificate and sets the env).
import crypto from 'node:crypto';
import fs from 'node:fs';
import https from 'node:https';
import path from 'node:path';

const dir = process.env.HARNESS_DIR;
const port = Number(process.env.RADAR_HOOK_PORT || 9381);
const log = path.join(dir, 'webhook-received.jsonl');
const secretsFile = path.join(dir, 'webhook-secrets.txt');

/** docs/webhook.md → "Verifying the signature" → Node.js, verbatim. */
export function verifyRadar(rawBody, header, secret, toleranceSec = 300) {
  const parts = Object.fromEntries(String(header || '').split(',').map(p => p.split('=')));
  const t = Number(parts.t);
  if (!t || !parts.v1 || Math.abs(Date.now() / 1000 - t) > toleranceSec) return false;
  const expected = crypto.createHmac('sha256', secret).update(`${t}.${rawBody}`).digest('hex');
  const a = Buffer.from(expected), b = Buffer.from(parts.v1);
  return a.length === b.length && crypto.timingSafeEqual(a, b);
}

const secrets = () => [process.env.RADAR_IT_WEBHOOK_SECRET, ...(fs.existsSync(secretsFile) ? fs.readFileSync(secretsFile, 'utf8').split('\n') : [])].map(s => (s || '').trim()).filter(Boolean);
const posts = new Map(); // slug → article, rebuilt from the log on start
if (fs.existsSync(log)) for (const l of fs.readFileSync(log, 'utf8').split('\n')) { try { const r = JSON.parse(l); const a = r.verified && r.body?.data?.article; if (a?.slug) posts.set(a.slug, a); } catch { /* */ } }
const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const send = (res, status, body, type = 'application/json') => { res.writeHead(status, { 'content-type': type }); res.end(typeof body === 'string' ? body : JSON.stringify(body)); };

const server = https.createServer({ key: fs.readFileSync(path.join(dir, 'webhook-key.pem')), cert: fs.readFileSync(path.join(dir, 'webhook-cert.pem')) }, (req, res) => {
  const u = new URL(req.url, `https://localhost:${port}`);
  if (req.method === 'GET' && u.pathname === '/__received') {
    const rows = fs.existsSync(log) ? fs.readFileSync(log, 'utf8').trim().split('\n').filter(Boolean).map(l => JSON.parse(l)) : [];
    const id = u.searchParams.get('id');
    return send(res, 200, id ? rows.filter(r => r.body?.data?.article?.id === id || r.headers['idempotency-key'] === id) : rows);
  }
  if (req.method === 'GET' && u.pathname.startsWith('/posts/')) {
    const a = posts.get(decodeURIComponent(u.pathname.slice('/posts/'.length)));
    if (!a) return send(res, 404, 'Not found', 'text/plain');
    const img = a.featured_image ? `<img src="${esc(a.featured_image.url)}" alt="${esc(a.featured_image.alt)}">` : '';
    return send(res, 200, `<!doctype html><meta charset="utf-8"><title>${esc(a.title)}</title><meta name="description" content="${esc(a.meta_description)}"><h1>${esc(a.title)}</h1>${img}\n${a.html}`, 'text/html; charset=utf-8');
  }
  if (req.method !== 'POST') return send(res, 405, { error: 'method' });
  const chunks = [];
  req.on('data', c => chunks.push(c));
  req.on('end', () => {
    const raw = Buffer.concat(chunks).toString('utf8');
    const header = req.headers['radar-signature'];
    const verified = secrets().some(s => verifyRadar(raw, header, s));
    let body = null; try { body = JSON.parse(raw); } catch { /* recorded as null */ }
    const forced = Number(u.searchParams.get('status')) || 0;
    const reason = !verified ? 'bad signature' : forced ? `forced ${forced}` : 'ok';
    fs.appendFileSync(log, JSON.stringify({ at: new Date().toISOString(), path: u.pathname + u.search, headers: req.headers, verified, reason, body }) + '\n');
    console.log(`${new Date().toISOString()} ${req.headers['radar-event']} ${verified ? 'verified' : 'BAD SIGNATURE'} ${forced ? '→ ' + forced : ''}`);
    if (!verified) return send(res, 401, 'bad signature', 'text/plain');
    if (forced) return send(res, forced, { error: 'forced' });
    const a = body?.type === 'article.published' ? body.data?.article : null;
    if (a?.slug) { posts.set(a.slug, a); return send(res, 200, { ok: true, url: `https://localhost:${port}/posts/${encodeURIComponent(a.slug)}` }); }
    return send(res, 200, { ok: true });
  });
});
server.listen(port, () => console.log(`Radar webhook receiver on https://localhost:${port}/hook (log: ${log})`));
